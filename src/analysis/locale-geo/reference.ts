/**
 * Parse the primary Accept-Language value. Accepts forms like:
 *   "en-US,en;q=0.9,fr;q=0.7"  →  { lang: "en", country: "US" }
 *   "zh-CN"                     →  { lang: "zh", country: "CN" }
 *   "fr"                        →  { lang: "fr", country: null }
 *   "en-GB-oxendict"            →  { lang: "en", country: "GB" }
 *   ""                          →  null
 */
export function parseAcceptLanguage(
  header: string | null | undefined,
): { lang: string; country: string | null } | null {
  if (!header || typeof header !== "string") return null;
  const first = header.split(",")[0]?.trim();
  if (!first) return null;
  const tag = first.split(";")[0]?.trim();
  if (!tag) return null;
  const parts = tag.split("-");
  const lang = parts[0]?.toLowerCase();
  if (!lang || !/^[a-z]{2,3}$/.test(lang)) return null;
  // Find first 2-letter uppercase-ish segment → country
  for (const p of parts.slice(1)) {
    if (/^[A-Za-z]{2}$/.test(p)) return { lang, country: p.toUpperCase() };
  }
  return { lang, country: null };
}
